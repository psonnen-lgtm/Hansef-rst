const write=(p,x)=>fs.writeFileSync(path.join(directory,p),JSON.stringify(x,null,2)+'\n');
const seeds=[81001,81002,81003],routes=[
 {id:'luebeck-hamburg',cities:[0,1],goods:[3,1]},
 {id:'bergen-luebeck',cities:[6,0],goods:[4,0]},
 {id:'nowgorod-bruegge',cities:[9,8],goods:[10,5]}
],policies=['small22','largeCashLimited90'],models=Object.keys(PARAMETERS);
const plan={seeds,routes,policies,models,parameters:PARAMETERS,maximumArms:54,maxTrips:12,maxDays:120,maxDecisions:30,
 model:'fixed anchored stock target, integer marginal edges; no parameter tuning',
 policy:'fixed declared goods and alternating route; only local stock, quote, cash and own hold; reserve Kogge fee 6',
 information:'no remote reads, no new paid information; costs 0 in both arms; existing letters still generated by actual clock',
 hazard:'actual seeded rollTravel/arrive, no disabled risk arm',
 gameHash:hash(html),testedCommit:execFileSync('git',['rev-parse','HEAD'],{cwd:root,encoding:'utf8'}).trim()};
