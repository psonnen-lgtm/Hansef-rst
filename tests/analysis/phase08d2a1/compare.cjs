const historical=JSON.parse(fs.readFileSync(path.join(historicalDirectory,'summary.json')));
assert.equal(plan.gameHash,historical.plan.gameHash);
const prototypeFiles=['quantity-model.cjs','harness.cjs','compare.cjs'].map(name=>({name,sha256:hash(fs.readFileSync(path.join(__dirname,name)))}));
