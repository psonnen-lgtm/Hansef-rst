const rows=[];
for(const seed of seeds)for(const route of routes){
 const fixtureId=`${route.id}-${seed}`;
 const initial=JSON.parse(fs.readFileSync(path.join(historicalDirectory,`start-${fixtureId}.json`)));
 const initialHash=hash(JSON.stringify(initial));
 assert.equal(initial.gameHash,plan.gameHash);
 write(`start-reference-${fixtureId}.json`,{source:path.relative(root,path.join(historicalDirectory,`start-${fixtureId}.json`)),sha256:hash(fs.readFileSync(path.join(historicalDirectory,`start-${fixtureId}.json`))),canonicalHash:initialHash});
 for(const policy of policies)for(const model of models){
  const start=clean(initial);start.model=model;start.parameter=PARAMETERS[model];
  const g=create(seed,route.cities[0],model,start),startGame=g.state(),startDay=g.eval('totalDay()');
  assert.deepEqual(startGame,initial.game);assert.deepEqual(g.rng(),initial.rng);
  const legs=[];let decisions=0,reason='maxTrips',minimumCash=startGame.gold,emptyTrips=0,goldConstrainedPurchases=0,zeroPurchasesForGold=0;
  for(let trip=0;trip<12;trip++){
   if(decisions>=30){reason='maxDecisions';break}
   const side=trip%2,dest=route.cities[1-side],good=route.goods[side],elapsed=g.eval('totalDay()')-startDay;
   if(elapsed>=120){reason='maxDays';break}
   // Dry planning uses own ship, map distance and local cash, no random or remote markets.
   g.eval(`pending=null;planTravel(${dest},false);`);const pending=clean(g.eval('pending'));
   if(!pending){reason='cannotPayDepartureFee';break}
   if(elapsed+pending.days>120){reason='nextTripExceeds120';break}
   const local=g.state().markets[g.state().city][good];
   const quantity=Math.min(policy==='small22'?22:90,g.max(good,6));
   const decisionInput={city:g.state().city,good,stock:local.stock,initialPrice:local.price,cash:g.state().gold,free:g.eval('capacity()-load()'),reserve:6};
   const desired=Math.min(policy==='small22'?22:90,local.stock,decisionInput.free);
   const constrainedByGold=quantity<desired;
   if(constrainedByGold)goldConstrainedPurchases++;
   if(constrainedByGold&&quantity===0)zeroPurchasesForGold++;
   const quote=quantity?g.quote(good,quantity,1):null;decisions++;
   const buy=quantity?g.trade(good,quantity,1):null;if(quantity)assert(buy,'bounded planned buy failed');else emptyTrips++;
   minimumCash=Math.min(minimumCash,g.state().gold);
   const cargoBefore=clean(g.eval('ship()')),eventStart=g.events.length;
   g.eval('arrive();validate(s)');const travelEvents=g.events.slice(eventStart),travel=travelEvents.find(e=>e.type==='travel');assert(travel);
   const actual=g.eval(`ship().cargo[${good}]||0`);const arrivedMarket=clean(g.eval(`s.markets[s.city][${good}]`));decisions++;
   const sale=actual?g.trade(good,actual,-1):null;if(actual)assert(sale);
   const pirate=travelEvents.filter(e=>e.type==='pirate_loss').reduce((s,e)=>s+e.quantity*(e.averageCost??0),0);
   minimumCash=Math.min(minimumCash,g.state().gold);g.eval('validate(s)');
   assert(g.state().gold>=0);assert(g.eval('load()<=capacity()'));
   legs.push({trip:trip+1,decisionInput,desired,constrainedByGold,arrivedMarket,quote,buy,sale,travel,pirateBookLoss:pirate,cargoBefore,elapsed:g.eval('totalDay()')-startDay,cash:g.state().gold,free:g.eval('capacity()-load()')});
  }
  const end=g.state(),days=g.eval('totalDay()')-startDay,buys=legs.filter(x=>x.buy).map(x=>x.buy),sales=legs.filter(x=>x.sale).map(x=>x.sale);
  const sum=(a,k)=>a.reduce((s,x)=>s+(x[k]??0),0);
  const buyCost=sum(buys,'total'),revenue=sum(sales,'total'),profit=sum(sales,'profit'),fees=legs.reduce((s,l)=>s+l.travel.fee,0),loss=legs.reduce((s,l)=>s+l.pirateBookLoss,0);
  const remainingCost=g.eval('cargoWorth()+warehouseWorth()'),net=profit-fees-loss;
  assert(Math.abs(end.gold-(5000-buyCost+revenue-fees))<1e-7,'cash ledger');
  assert(Math.abs(end.gold-(5000+net-remainingCost))<1e-7,'realization ledger');
  const row={id:`${fixtureId}-${policy}-${model}`,seed,route:route.id,policy,model,initialHash,initialGameHash:hash(JSON.stringify(startGame)),
   stop:reason,trips:legs.length,days,decisions,bought:sum(buys,'quantity'),sold:sum(sales,'quantity'),buyCost,revenue,realizedProfit:profit,fees,pirateBookLoss:loss,net,
   profitPerSoldBarrel:sum(sales,'quantity')?profit/sum(sales,'quantity'):null,profitPerDay:days?profit/days:null,netPerDay:days?net/days:null,
   cash:end.gold,minimumCash,netWorth:g.eval('netWorth()'),politicalWorth:g.eval('politicalWorth()'),debt:end.debt,bank:end.bank,creditUsed:0,creditAvailable:g.eval('creditLimit()-s.debt'),
   openInventoryCost:remainingCost,openInventory:g.eval('load()+Object.values(s.warehouses).reduce((a,w)=>a+Object.values(w.cargo).reduce((n,v)=>n+v,0),0)'),
   freeHold:g.eval('capacity()-load()'),negativeSales:sales.filter(e=>e.profit<0).length,emptyTrips,goldConstrainedPurchases,zeroPurchasesForGold,failedExecutedPurchases:0,endCanPayFee:end.gold>=6,meanUnusedHold:legs.length?legs.reduce((n,l)=>n+90-(l.buy?.quantity||0),0)/legs.length:null,travelBlock:reason==='cannotPayDepartureFee',
   economicDeadEndProven:false,informationCosts:0,rep:end.rep,rank:end.rank,lettersGenerated:end.information.letters.index,condition:end.ships[0].condition,
   goods:clean(g.eval('GOODS')).filter((_,j)=>route.goods.includes(j)).map(x=>x[0]),
   goodsSold:Object.fromEntries([...new Set(sales.map(e=>e.good))].map(good=>[good,sales.filter(e=>e.good===good).reduce((s,e)=>s+e.quantity,0)])),rng:g.rng()};
  write(`${row.id}.json`,{metrics:row,legs,events:g.events,end:g.snapshot()});rows.push(row);console.log(`${rows.length}/54 ${row.id} trips=${row.trips} days=${days} profit=${profit.toFixed(2)} cash=${end.gold}`);
 }
}
